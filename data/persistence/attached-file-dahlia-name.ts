import type { Prisma, PrismaClient } from "@prisma/client";
import {
  fieldChangeTargetAttachedFile,
  hasFieldChangeBy,
  recordFieldChange,
} from "../../app/lib/field-change";

// Who renamed a pièce, stored as `origin` in the `field_changes` history.
export type DahliaNameOrigin = "user" | "scraper" | "script";

export const DAHLIA_NAME_FIELD = "dahliaName";

export const USER_ORIGIN: DahliaNameOrigin = "user";

// A date at the head of a file name (2025-01-17, 18_05_18, 21.01.2025) is kept
// as text rather than split into piece numbers.
const LEADING_DATE =
  /^(?:\d{4}-\d{2}-\d{2}|\d{1,2}[_.-]\d{1,2}[_.-](?:\d{4}|\d{2}))(?=[^\p{L}\p{N}]|$)/u;
// Piece label before its number (P_34, PJ5, PJ_1, Piece_33, piece_n_4, Pièce n°3).
const PIECE_PREFIX = /^(?:PJ|P|Pi[eè]ces?)[^\p{L}\p{N}]*(?:n[°o]?[^\p{L}\p{N}]*)?(?=\d)/iu;
const LEADING_NUMBER = /^(\d+)[^\p{L}\p{N}]*/u;
// Words Telerecours glues in its generated file names, spelled out for display
// (e.g. "1105771952_inventaireAutomatique_803008652.pdf").
const WORD_REPLACEMENTS: [RegExp, string][] = [
  [/(?<![\p{L}\p{N}])inventaireAutomatique(?![\p{L}\p{N}])/giu, "Inventaire automatique"],
];

// Derive a Dahlia display name from a Telerecours file name: drop the ".pdf"
// extension and piece prefixes (P_, PJ, Pièce n°…), zero-pad every leading
// number to at least 3 digits, keep leading dates as text, then replace
// underscores with single spaces in the remaining text.
// e.g. "P_20261021_34_requête.pdf" → "20261021 034 requête". Returns null
// when nothing is left.
export function pieceNameFromFileName(fileName: string): string | null {
  let rest = fileName.replace(/\.pdf$/i, "");
  const numbers: string[] = [];
  while (!LEADING_DATE.test(rest)) {
    rest = rest.replace(PIECE_PREFIX, "");
    const match = rest.match(LEADING_NUMBER);
    if (!match) break;
    numbers.push(match[1].padStart(3, "0"));
    rest = rest.slice(match[0].length);
  }
  const text = WORD_REPLACEMENTS.reduce(
    (current, [pattern, replacement]) => current.replace(pattern, replacement),
    rest.replace(/_/g, " ").replace(/\s+/g, " ").trim(),
  );
  const name = [...numbers, text].filter(Boolean).join(" ");
  return name || null;
}

// Court correspondence (family COUK) is generated by the court software and
// named "<id>_<code>.pdf" or "<code>_<id>.pdf" (1083731924_notreq.pdf,
// notjuge_1167250019.pdf, r611-11_1164887605.pdf): the id is internal and the
// code (notreq, comrqsoc, letgre…) always stands for the piece type (checked on
// the whole TA069 base: 83 codes, each tied to exactly one fileTypeLabel and
// never used outside COUK). The code is replaced by the type label, and the id
// is kept where it stands.
const COURT_CORRESPONDENCE_FAMILY = "COUK";
const ID_THEN_CODE_FILE_NAME = /^(\d+)_[a-z][a-z0-9-]*\.pdf$/i;
const CODE_THEN_ID_FILE_NAME = /^[a-z][a-z0-9-]*_(\d+)\.pdf$/i;

export type AutoNamedPiece = {
  fileName: string;
  fileTypeLabel?: string | null;
  fileFamilyTypeCode?: string | null;
};

// Automatic Dahlia name of a pièce: for code-named court correspondence, its
// type label with the id kept in place ("1083731924_notreq.pdf" →
// "1083731924 Communication de la requête", "notjuge_1167250019.pdf" →
// "Notification de jugement 1167250019"); otherwise the name derived from its
// file name.
export function autoDahliaName(piece: AutoNamedPiece): string | null {
  const typeLabel = piece.fileTypeLabel?.trim();
  if (typeLabel && piece.fileFamilyTypeCode === COURT_CORRESPONDENCE_FAMILY) {
    const idFirst = piece.fileName.match(ID_THEN_CODE_FILE_NAME);
    if (idFirst) return `${idFirst[1]} ${typeLabel}`;
    const idLast = piece.fileName.match(CODE_THEN_ID_FILE_NAME);
    if (idLast) return `${typeLabel} ${idLast[1]}`;
  }
  return pieceNameFromFileName(piece.fileName);
}

// Telerecours-owned fields of an attached file, as written by the scraper.
export type AttachedFileTelerecoursData = {
  originalFileName: string;
  fileName: string;
  mimeType: string;
  documentType: string;
  subEventId: number;
  receiptAcknowledgmentId: number | null;
  receiptAcknowledgmentType: string | null;
  fileTypeLabel: string;
  fileFamilyTypeLabel: string | null;
  eventCreationDate: Date;
  caseFileNumber: string;
  eventId: number;
  fileFamilyTypeCode: string;
};

const TELERECOURS_FIELDS = [
  "originalFileName",
  "fileName",
  "mimeType",
  "documentType",
  "subEventId",
  "receiptAcknowledgmentId",
  "receiptAcknowledgmentType",
  "fileTypeLabel",
  "fileFamilyTypeLabel",
  "eventCreationDate",
  "caseFileNumber",
  "eventId",
  "fileFamilyTypeCode",
] as const satisfies readonly (keyof AttachedFileTelerecoursData)[];

// True when the scraped payload differs from the stored Telerecours fields.
export function hasTelerecoursChanges(
  stored: AttachedFileTelerecoursData,
  scraped: AttachedFileTelerecoursData,
): boolean {
  return TELERECOURS_FIELDS.some((field) => {
    const before = stored[field];
    const after = scraped[field];
    if (before instanceof Date && after instanceof Date) {
      return before.getTime() !== after.getTime();
    }
    // Treat undefined (absent from the payload) as null.
    return (before ?? null) !== (after ?? null);
  });
}

// Whether an automatic rename (scraper or script) may overwrite the name:
//   - default: only when the name is still empty;
//   - force: also a named pièce, unless a user renamed it at least once (its
//     name was then chosen by an agent). Names set by the scraper or a script,
//     and names without history, are recomputed.
export function mayAutoRename(
  piece: { dahliaName: string | null },
  renamedByUser: boolean,
  force: boolean,
): boolean {
  if (!piece.dahliaName) return true;
  return force && !renamedByUser;
}

// Name an automatic rename would write, or null when there is nothing to do
// (no name derivable, rename not allowed, or same name).
export function plannedAutoRename(
  piece: AutoNamedPiece & { dahliaName: string | null },
  renamedByUser: boolean,
  force: boolean,
): string | null {
  const name = autoDahliaName(piece);
  if (!name || name === piece.dahliaName) return null;
  return mayAutoRename(piece, renamedByUser, force) ? name : null;
}

// Whether an agent renamed the pièce at least once (history origin "user").
export function wasRenamedByUser(
  db: Pick<PrismaClient, "fieldChange">,
  jurisdictionCode: string,
  encodedFileId: string,
): Promise<boolean> {
  return hasFieldChangeBy(
    db,
    fieldChangeTargetAttachedFile(jurisdictionCode, encodedFileId),
    DAHLIA_NAME_FIELD,
    USER_ORIGIN,
  );
}

export type DahliaNamePiece = {
  jurisdictionCode: string;
  encodedFileId: string;
  dahliaName: string | null;
};

// Write the pièce (new name, `otherData`, `updatedAt`) and, when the name
// actually changes, its history row, in a single transaction. A cleared name
// is stored as null and logged with an empty `newValue`. Returns whether the
// name changed.
export async function applyDahliaNameUpdate(
  db: PrismaClient,
  piece: DahliaNamePiece,
  newName: string | null,
  origin: DahliaNameOrigin,
  options: { otherData?: Prisma.AttachedFileUpdateInput; now?: Date } = {},
): Promise<boolean> {
  const { jurisdictionCode, encodedFileId } = piece;
  const previousName = piece.dahliaName || null;
  const renamed = (newName || null) !== previousName;
  const now = options.now ?? new Date();

  await db.$transaction([
    db.attachedFile.update({
      where: { jurisdictionCode_encodedFileId: { jurisdictionCode, encodedFileId } },
      data: { ...options.otherData, dahliaName: newName || null, updatedAt: now },
    }),
    ...(renamed
      ? [
          recordFieldChange(db, fieldChangeTargetAttachedFile(jurisdictionCode, encodedFileId), {
            field: DAHLIA_NAME_FIELD,
            previousValue: previousName,
            newValue: newName ?? "",
            origin,
            changedAt: now,
          }),
        ]
      : []),
  ]);
  return renamed;
}
